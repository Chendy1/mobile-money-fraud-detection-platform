"""Figures and the Markdown report for Phase 8. Every number is computed from the run."""

from __future__ import annotations

from pathlib import Path

from mmrisk.models import figures as F
from mmrisk.models import figures_advanced as FA
from mmrisk.models.advanced import SCORERS, AdvancedResult
from mmrisk.models.boosting import STAGES
from mmrisk.models.costs import CostModel
from mmrisk.models.metrics import interval

ORDER = ["no_skill", "rules", "logistic_regression", "random_forest", "lightgbm"]
LABEL = {m: v[3] for m, v in F.STYLE.items()}
FIG = {
    "pr": "04-precision-recall-advanced.png",
    "calibration": "05-calibration.png",
    "map": "06-decision-map.png",
    "cost": "07-cost.png",
}
INK_GREY = "#8A8F98"


def pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def ci_text(point: float, ci: tuple[float, float], d: int = 3) -> str:
    return f"{point:.{d}f} ({ci[0]:.{d}f} to {ci[1]:.{d}f})"


def kes(x: float) -> str:
    return f"{x:,.0f}"


def md(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def verdict(lo: float, hi: float, higher: str = "higher", lower: str = "lower") -> str:
    if lo > 0:
        return f"{higher} (the interval excludes zero)"
    if hi < 0:
        return f"{lower} (the interval excludes zero)"
    return "not separable from zero (the interval includes zero)"


def diff(boot: dict, point: dict, a: str, b: str) -> tuple[float, tuple[float, float]]:
    return point[a] - point[b], interval(boot[a] - boot[b])


def write(
    *, split, models, lgbm_grid, val, test, calib, cm: CostModel, cost, stats, sensitivity,
    prevents, audit, naive_blocks, n_test, cost_boot, concentration, report_path: Path, figures_dir: Path,
    seed: int, quick: bool, y_test,
) -> AdvancedResult:  # fmt: skip
    fig = {k: figures_dir / v for k, v in FIG.items()}
    prevalence = float(y_test.mean())
    ap = {n: test[n]["point"]["pr_auc"] for n in ORDER}
    F.pr_curves(y_test, test["_scores"], ap, prevalence, fig["pr"])
    FA.calibration(calib["raw_rows"], calib["cal_rows"], fig["calibration"])
    FA.decision_map(cm, fig["map"])
    colour = {n: F.STYLE[n][0] for n in ORDER}
    bar_rows = [
        {"label": "Allow everything", "colour": INK_GREY, **_bar(cost["allow_all"])},
        {"label": "LightGBM, raw score >= 0.5 blocks", "colour": "#E5B8D0", **_bar(cost["naive"])},
    ]
    bar_rows += [
        {"label": f"{LABEL[n]}, calibrated + cost rule", "colour": colour[n], **_bar(cost[n])}
        for n in SCORERS
    ]
    bar_rows.append(
        {"label": "Perfect knowledge (oracle)", "colour": "#1f2328", **_bar(cost["oracle"])}
    )
    FA.cost_by_scorer(bar_rows, sensitivity, fig["cost"])

    rel = (
        figures_dir.relative_to(report_path.parent).as_posix()
        if figures_dir.is_relative_to(report_path.parent)
        else figures_dir.as_posix()
    )
    boot_ap = test["_boot_pr_auc"]
    d_rf = diff(boot_ap, ap, "lightgbm", "random_forest")
    d_lr = diff(boot_ap, ap, "lightgbm", "logistic_regression")
    d_ru = diff(boot_ap, ap, "lightgbm", "rules")
    rf_minus_lg_cost = interval(cost_boot["random_forest"] - cost_boot["lightgbm"])
    rf_lg_point = cost["random_forest"]["point"] - cost["lightgbm"]["point"]
    best = min(SCORERS, key=lambda n: cost[n]["point"])
    lg = stats["lightgbm"]
    best_cfg = lgbm_grid.sort("val_pr_auc", descending=True).row(0, named=True)
    imp = sorted(models["lightgbm"].gain_importance().items(), key=lambda kv: -kv[1])[:8]
    ece_raw, ece_cal = calib["ece"]["lightgbm raw"], calib["ece"]["lightgbm"]
    brier_raw, brier_cal = calib["brier"]["lightgbm raw"], calib["brier"]["lightgbm calibrated"]
    brier_const = calib["brier"]["constant (training fraud rate)"]
    a_lg, b_lg = calib["platt"]["lightgbm"]
    weights_hurt = (
        lgbm_grid.filter(lgbm_grid["class_weight"] == "none")["val_pr_auc"].max()
        > lgbm_grid.filter(lgbm_grid["class_weight"] == "balanced")["val_pr_auc"].max()
        if (lgbm_grid["class_weight"] == "balanced").any()
        else None
    )

    L: list[str] = []
    add = L.append
    add("# Advanced model, calibration and cost-based decisions")
    add("")
    add(
        "> **All data is synthetic, and every cost in this report is an assumption.** The costs "
        "(review, friction, share of fraud a review stops) are placeholders chosen for this "
        'simulation, not measurements from any provider. Savings are therefore "under these '
        'assumptions", never a claim about real money. Generated by `python -m mmrisk.models '
        "advanced`; every number below is computed from the run."
    )
    add("")
    add("## Key results")
    add("")
    add(
        f"- **Ranking.** LightGBM test PR-AUC is {ci_text(ap['lightgbm'], test['lightgbm']['ci']['pr_auc'], 2)}"
        f" against {ap['random_forest']:.2f} for the random forest and {ap['logistic_regression']:.2f} "
        f"for logistic regression (fraud rate {pct(prevalence, 2)}). Difference to the random forest: "
        f"{d_rf[0]:+.2f} ({d_rf[1][0]:+.2f} to {d_rf[1][1]:+.2f}), "
        f"{verdict(*d_rf[1], higher='LightGBM higher', lower='LightGBM lower')}. "
        f"Difference to logistic regression: {d_lr[0]:+.2f} ({d_lr[1][0]:+.2f} to {d_lr[1][1]:+.2f}), "
        f"{verdict(*d_lr[1], higher='LightGBM higher', lower='LightGBM lower')}."
    )
    add(
        f"- **Probabilities.** Calibration on the validation window changed LightGBM's calibration "
        f"error on the test window from {ece_raw:.4f} to {ece_cal:.4f} (lower is better) and its Brier "
        f"score from {brier_raw:.5f} to {brier_cal:.5f}; a constant guess scores {brier_const:.5f}."
    )
    add(
        f"- **Decisions.** With the assumed costs, the scorer with the lowest cost on the test period "
        f"is **{LABEL[best]}**: {kes(cost[best]['point'])} KES per 10,000 transactions against "
        f"{kes(cost['allow_all']['point'])} for allowing everything "
        f"({pct(cost[best]['saving'], 0)} lower), with perfect knowledge at {kes(cost['oracle']['point'])}. "
        f"LightGBM's saving is {pct(cost['lightgbm']['saving'], 0)}."
    )
    add(
        f"- **LightGBM versus the random forest in cost.** Random forest cost minus LightGBM cost is "
        f"{rf_lg_point:+,.0f} KES per 10,000 ({rf_minus_lg_cost[0]:+,.0f} to {rf_minus_lg_cost[1]:+,.0f}): "
        f"{verdict(*rf_minus_lg_cost, higher='LightGBM cheaper', lower='random forest cheaper')}."
    )
    add(
        f"- **A fixed 0.5 cut-off is the wrong tool.** Blocking when LightGBM's raw score is at least "
        f"0.5 blocks {naive_blocks} of {n_test:,} test transactions and costs "
        f"{kes(cost['naive']['point'])} KES per 10,000 "
        f"({pct(cost['naive']['saving'], 0)} lower than allowing everything); the cost rule above does "
        f"better by {kes(cost['naive']['point'] - cost['lightgbm']['point'])} KES per 10,000."
    )
    if concentration["top5_share"] > 0.5:
        why = "so a handful of transactions drives the cost and the order of scorers is fragile."
    else:
        why = (
            "so cost is not driven by a handful of transactions; the wide intervals come from the "
            "small number of fraud cases, which also come in clusters by customer."
        )
    add(
        f"- **Spread of the fraud amounts.** The 5 largest fraud-labelled amounts make "
        f"{pct(concentration['top5_share'], 0)} of the {kes(concentration['total'])} KES fraud total in "
        f"the test period (median fraud {kes(concentration['median'])} KES, largest "
        f"{kes(concentration['largest'])}), {why}"
    )
    add("")
    add("## 1. Does a gradient-boosted model rank fraud better than the baselines?")
    add("")
    add(f"![precision recall]({rel}/{FIG['pr']})")
    add("")
    add(
        "LightGBM was tuned like the other models: settings and number of boosting rounds chosen "
        "on the validation window only (no early stopping inside training, so the training part "
        "never sees validation), then the test window scored once. Each row is one setting; "
        '"Best rounds" and "Validation PR-AUC" are the best of the stopping points tried '
        f"({', '.join(str(s) for s in ((25, 50, 100) if quick else STAGES))} rounds)."
    )
    add("")
    add(
        md(
            [
                "Leaves",
                "Min rows per leaf",
                "Class weight",
                "Best rounds",
                "Validation PR-AUC",
                "Chosen",
            ],
            [
                [
                    str(r["num_leaves"]),
                    str(r["min_child_samples"]),
                    r["class_weight"],
                    str(r["rounds"]),
                    f"{r['val_pr_auc']:.3f}",
                    "yes" if r == best_cfg else "",
                ]
                for r in lgbm_grid.iter_rows(named=True)
            ],
        )
    )
    add("")
    spread = lgbm_grid.filter(lgbm_grid["class_weight"] == "none")["val_pr_auc"]
    add(
        f"Among unweighted settings the validation PR-AUC spans only {spread.min():.3f} to "
        f"{spread.max():.3f}: the model family is not the limiting factor, and the tuning grid "
        "cannot be expected to change the picture."
        + (
            " Class weighting lowered validation PR-AUC again, as it did for the Phase 7 models."
            if weights_hurt
            else ""
        )
    )
    add("")
    add(
        md(
            ["Model", "Test PR-AUC (95% interval)", "Validation PR-AUC"],
            [
                [
                    LABEL[n],
                    ci_text(ap[n], test[n]["ci"]["pr_auc"]),
                    f"{val[n]['point']['pr_auc']:.3f}",
                ]
                for n in ORDER
            ],
        )
    )
    add("")
    add(
        f"Paired differences (same customer resamples): LightGBM minus rules {d_ru[0]:+.2f} "
        f"({d_ru[1][0]:+.2f} to {d_ru[1][1]:+.2f}); minus random forest {d_rf[0]:+.2f} "
        f"({d_rf[1][0]:+.2f} to {d_rf[1][1]:+.2f}); minus logistic regression {d_lr[0]:+.2f} "
        f"({d_lr[1][0]:+.2f} to {d_lr[1][1]:+.2f}). Only differences whose interval excludes zero "
        "should be read as real."
    )
    add("")
    add(
        "Top features by gain (a rough preview; proper explanations come in Phase 9): "
        + ", ".join(f"`{k}` {pct(v, 0)}" for k, v in imp)
        + "."
    )
    add("")
    add("## 2. Can the scores be read as probabilities?")
    add("")
    add(f"![calibration]({rel}/{FIG['calibration']})")
    add("")
    add(
        "A probability has to be right before it can be used to price a decision. Scores were "
        "calibrated with Platt scaling (a two-parameter logistic curve) fitted on the validation "
        f"window only; for LightGBM p = sigmoid({a_lg:.2f} x logit(score) {b_lg:+.2f}). The chart "
        "groups test transactions by the probability given and shows how many really were fraud; "
        "points on the dashed line are perfect, and groups with no fraud cannot be drawn on a log scale "
        "(they are in the table)."
    )
    add("")
    add(
        md(
            [
                "Probability group",
                "Transactions",
                "Fraud",
                "Predicted (calibrated)",
                "Observed (95% interval)",
            ],
            [
                [
                    f"{r['low']:g} to {r['high']:g}",
                    f"{r['rows']:,}",
                    str(r["fraud"]),
                    pct(r["predicted"], 2),
                    f"{pct(r['observed'], 2)} ({pct(r['ci_low'], 2)} to {pct(r['ci_high'], 2)})",
                ]
                for r in calib["cal_rows"]
            ],
        )
    )
    add("")
    add(
        f"The validation window has a fraud rate of {pct(calib['val_rate'], 2)} and the test window "
        f"{pct(calib['test_rate'], 2)}. A calibrator fitted on one window carries that rate with it, so some "
        "gap on the next window is expected; this is a reason to re-check calibration regularly (Phase 14)."
    )
    add("")
    top = calib["cal_rows"][-1]
    if top["ci_high"] < top["predicted"]:
        gap = "overconfident: the model's probability is above the observed rate (interval excludes the prediction)"
    elif top["ci_low"] > top["predicted"]:
        gap = "underconfident: the observed rate is above the model's probability (interval excludes the prediction)"
    else:
        gap = "consistent with the observed rate (the interval includes the prediction)"
    add(
        f"In the highest-probability group ({top['low']:g} to {top['high']:g}, {top['rows']} transactions) "
        f"the model gives {pct(top['predicted'], 0)} on average and {pct(top['observed'], 0)} were fraud "
        f"({pct(top['ci_low'], 0)} to {pct(top['ci_high'], 0)}): {gap}."
    )
    add("")
    add(
        md(
            ["Scorer", "Calibration error (test)", "Brier score (test)"],
            [["LightGBM, raw", f"{ece_raw:.4f}", f"{brier_raw:.5f}"]]
            + [
                [
                    f"{LABEL[n]}, calibrated",
                    f"{calib['ece'][n]:.4f}",
                    f"{calib['brier'][n + ' calibrated']:.5f}",
                ]
                for n in SCORERS
            ]
            + [["Constant guess (training fraud rate)", "n/a", f"{brier_const:.5f}"]],
        )
    )
    add("")
    add("## 3. The cost model (assumed)")
    add("")
    add(f"![decision map]({rel}/{FIG['map']})")
    add("")
    add(
        "Three actions, from the probability alone: **allow** (risk level LOW), **review** (MEDIUM: hold "
        "for a verification or an analyst) and **block** (HIGH: decline or require step-up authentication). "
        "The action with the lowest expected cost is chosen; no label is involved."
    )
    add("")
    add(
        md(
            ["Assumption", "Value", "Meaning"],
            [
                [
                    "Loss rate",
                    f"{cm.loss_rate:g}",
                    "Share of a fraudulent amount lost if it gets through (1 = nothing recovered)",
                ],
                [
                    "Review cost",
                    f"{cm.review_cost:g} KES",
                    "Paid on every review (analyst time, verification message)",
                ],
                ["Review prevents", pct(cm.review_prevents, 0), "Share of fraud a review stops"],
                [
                    "Block cost",
                    f"{cm.block_cost:g} KES",
                    "Friction paid when a legitimate transaction is blocked",
                ],
            ],
        )
    )
    add("")
    th = []
    for a in (100, 1_000, 10_000):
        r, b = cm.probability_thresholds(a)
        th.append(
            [f"{a:,} KES", "never" if r is None else pct(r, 1), "never" if b is None else pct(b, 1)]
        )
    add(md(["Amount", "Review from probability", "Block from probability"], th))
    add("")
    add(
        "Because the cost of letting fraud through grows with the amount, the same probability leads to "
        "a stricter action on a large transaction than on a small one."
    )
    add("")
    add("## 4. What does acting on the scores cost on the test period?")
    add("")
    add(f"![cost]({rel}/{FIG['cost']})")
    add("")
    rows = []

    def row(label, key, st=None):
        c = cost[key]
        rows.append(
            [
                label,
                f"{c['point']:,.0f} ({c['ci'][0]:,.0f} to {c['ci'][1]:,.0f})",
                pct(c["saving"], 0),
                "-" if st is None else f"{st['reviews_per_10k']:.0f}",
                "-" if st is None else f"{st['blocks_per_10k']:.0f}",
                "-" if st is None else pct(st["fraud_blocked"], 0),
                "-" if st is None else pct(st["fraud_reviewed"], 0),
                "-" if st is None else pct(st["fraud_missed"], 0),
            ]
        )

    row("Allow everything", "allow_all")
    row("LightGBM, raw score >= 0.5 blocks", "naive")
    for n in SCORERS:
        row(f"{LABEL[n]}, calibrated + cost rule", n, stats[n])
    row("Perfect knowledge (oracle)", "oracle")
    add(
        md(
            ["Policy", "Cost per 10,000 transactions, KES (95% interval)", "Saved vs allow-all",
             "Reviews per 10,000", "Blocks per 10,000", "Fraud blocked", "Fraud reviewed", "Fraud allowed"],
            rows,
        )
    )  # fmt: skip
    add("")
    add(
        f"LightGBM blocked {lg['legit_blocked']} legitimate transactions in the test period. Costs use the "
        "observed labels, which miss some fraud and include some false reports (section 5)."
    )
    add("")
    learned = ["logistic_regression", "random_forest", "lightgbm"]
    by_ap = sorted(learned, key=lambda n: -ap[n])
    by_cost = sorted(learned, key=lambda n: cost[n]["point"])
    if by_ap != by_cost:
        add(
            "PR-AUC treats every transaction equally, while the cost rule weights errors by amount, so "
            "the two measures can order scorers differently. Here the learned scorers rank "
            + " > ".join(LABEL[n] for n in by_ap)
            + " by PR-AUC and "
            + " < ".join(LABEL[n] for n in by_cost)
            + " by cost; the differences are within the intervals above."
        )
        add("")
    add("### Sensitivity to the assumed costs")
    add("")
    add(
        "The same calibrated probabilities, with the actions re-derived under other assumptions. "
        "Saving versus allowing everything (a larger number is better)."
    )
    add("")
    add(
        md(
            ["Review and block costs"] + [LABEL[n] for n in SCORERS],
            [
                [f"{f:g}x" + (" (assumed)" if f == 1.0 else "")]
                + [pct(sensitivity["savings"][n][i], 0) for n in SCORERS]
                for i, f in enumerate(sensitivity["factors"])
            ],
        )
    )
    add("")
    add(
        md(
            ["Share of fraud a review stops"] + [LABEL[n] for n in SCORERS],
            [
                [pct(pv, 0) + (" (assumed)" if pv == cm.review_prevents else "")]
                + [pct(sv[n], 0) for n in SCORERS]
                for pv, sv in prevents.items()
            ],
        )
    )
    add("")
    order_note = []
    for i in range(len(sensitivity["factors"])):
        order_note.append(max(SCORERS, key=lambda n, i=i: sensitivity["savings"][n][i]))
    if len(set(order_note)) == 1:
        add(f"{LABEL[order_note[0]]} has the largest saving at every friction level tried.")
    else:
        add(
            "The scorer with the largest saving changes with the assumed costs ("
            + ", ".join(
                f"{f:g}x: {LABEL[n]}"
                for f, n in zip(sensitivity["factors"], order_note, strict=True)
            )
            + "), so no scorer should be called best in cost terms without real cost figures."
        )
    add("")

    if audit is not None:
        add("## 5. Audit against ground truth")
        add("")
        add(
            "> **This section uses the hidden ground truth, which a real team would not have.** Nothing here "
            "influenced training, tuning, calibration or the decision rule."
        )
        add("")
        add(
            f"Against the true fraud flag ({audit['true_fraud']} true fraud rows in the test period) the "
            "scorers' PR-AUC and saving versus allowing everything are:"
        )
        add("")
        add(
            md(
                [
                    "Scorer",
                    "PR-AUC vs truth",
                    "Saving vs allow-all (true labels)",
                    "Saving (observed labels)",
                ],
                [
                    [
                        LABEL[n],
                        f"{audit['pr_auc'][n]:.2f}",
                        pct(audit["savings"][n], 0),
                        pct(cost[n]["saving"], 0),
                    ]
                    for n in SCORERS
                ],
            )
        )
        add("")
        add("What happens to each true fraud pattern under the LightGBM policy (test period):")
        add("")
        add(
            md(
                ["Pattern", "Rows", "Blocked", "Reviewed", "Allowed"],
                [
                    [
                        p["pattern"],
                        str(p["rows"]),
                        pct(p["blocked"], 0),
                        pct(p["reviewed"], 0),
                        pct(p["allowed"], 0),
                    ]
                    for p in audit["patterns"]
                ],
            )
        )
        add("")
    add("## What this does not show")
    add("")
    add(
        "- The data is simulated and the cost numbers are placeholders; the savings above say nothing about real money."
    )
    add(
        f"- The test period has {int(y_test.sum())} fraud-labelled transactions, so intervals are wide and "
        "differences between scorers are mostly not separable."
    )
    add(
        "- The author looked at one LightGBM test PR-AUC while building the code, before the grid was "
        "extended because the best setting sat at the edge of the first grid; no setting was changed to "
        "improve test results. The baselines come from the Phase 7 run unchanged."
    )
    add(
        "- Calibration is fitted on one validation window and measured on one test window with a different "
        "fraud rate; it is not guaranteed to hold later."
    )
    add(
        "- Review and block outcomes are modelled with fixed shares, not observed; a real review process "
        "has delays, errors and capacity limits that this does not capture."
    )
    add(
        "- Amount-based decisions assume the loss equals a fixed share of the amount; a real "
        "provider would also have limits, reversals and regulatory costs."
    )
    add("")
    text = "\n".join(L) + "\n"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(text, encoding="utf-8", newline="\n")
    metrics = {
        "test_pr_auc": ap,
        "validation_pr_auc": {n: val[n]["point"]["pr_auc"] for n in ORDER},
        "cost_per_10k": {
            k: {"point": v["point"], "ci": v["ci"], "saving": v["saving"]} for k, v in cost.items()
        },
        "calibration": {"ece": calib["ece"], "brier": calib["brier"]},
        "cost_model_ASSUMED": cm.as_dict(),
        "sensitivity": sensitivity,
        "seed": seed,
        "quick": quick,
    }
    return AdvancedResult(report_path, metrics, text)


def _bar(c: dict) -> dict:
    return {"cost": c["point"], "ci": c["ci"] if c["ci"][1] > c["ci"][0] else None}
