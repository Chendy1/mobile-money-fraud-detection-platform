"""Writes docs/model-card.md from the files the earlier steps saved. Every number is read, not typed.

Inputs, all in the model directory: risk_model.json (settings and calibration), advanced_metrics.json
(Phase 8) and explain_metrics.json (Phase 9). If one is missing the card is not written.
"""

from __future__ import annotations

import json
from pathlib import Path

CARD_FILES = ("risk_model.json", "advanced_metrics.json", "explain_metrics.json")


class CardError(ValueError):
    pass


def _pct(x: float, d: int = 0) -> str:
    return f"{100 * x:.{d}f}%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _versions() -> dict[str, str]:
    import importlib.metadata as md

    out = {}
    for pkg in ("lightgbm", "polars", "numpy", "scikit-learn"):
        try:
            out[pkg] = md.version(pkg)
        except md.PackageNotFoundError:
            out[pkg] = "not installed"
    return out


NAMES = {
    "no_skill": "No skill (random)",
    "rules": "Hand-written rules",
    "logistic_regression": "Logistic regression",
    "random_forest": "Random forest",
    "lightgbm": "LightGBM (shipped)",
}


def build(models_dir: Path) -> str:
    models_dir = Path(models_dir)
    missing = [f for f in CARD_FILES if not (models_dir / f).exists()]
    if missing:
        raise CardError(
            f"missing {', '.join(missing)} in {models_dir}; run `advanced` and `explain` first"
        )
    meta, adv, exp = (json.loads((models_dir / f).read_text()) for f in CARD_FILES)
    cm = adv["cost_model_ASSUMED"]
    params = meta["scorer_params"] or {}
    cal = meta["calibrator"]
    summ = {r["part"]: r for r in exp["split_summary"]}
    bounds = exp["split_bounds"]
    v = _versions()
    imp_all, imp_fr = exp["importance_all"], exp["importance_fraud_rows"]
    perm = exp["permutation"]
    ag = exp["agreement"]
    sl = [r for r in exp["slices"] if r["n"] >= 500]
    cost = adv["cost_per_10k"]
    ece, brier = adv["calibration"]["ece"], adv["calibration"]["brier"]
    base_cost = cost["allow_all"]["point"]

    L: list[str] = []
    L.append("# Model card: mmrisk LightGBM risk model\n")
    L.append("> **Synthetic data only.** This model was trained and evaluated on simulated mobile-money "
             "transactions. It is not affiliated with Safaricom or M-Pesa, it has never seen real customer "
             "data, and nothing here is evidence about real fraud or real money. Generated by "
             "`python -m mmrisk.models card` from the files the pipeline saved; every number is read from "
             "them.\n")  # fmt: skip

    L.append("## Model details\n")
    L.append(_table(["Item", "Value"], [
        ["Model", "Gradient-boosted trees (LightGBM), scored then calibrated, then turned into an action by an expected-cost rule"],
        ["Settings (chosen on the validation window)", f"{params.get('num_leaves')} leaves, at least {params.get('min_child_samples')} rows per leaf, class weight {'none' if params.get('pos_weight') == 1.0 else 'balanced'}, {meta.get('rounds')} boosting rounds"],
        ["Calibration", f"Platt scaling fitted on the validation window: calibrated log-odds = {cal['a']:.2f} x raw log-odds {cal['b']:+.2f}"],
        ["Feature set", f"version {meta['feature_version']}, 28 features ([catalog](feature-catalog.md))"],
        ["Created", meta["created_at"]],
        ["Libraries", ", ".join(f"{k} {x}" for k, x in v.items())],
        ["Author and licence", "Clyde Adili; Apache-2.0"],
        ["Decisions", "ALLOW (risk level LOW), REVIEW (MEDIUM), BLOCK (HIGH)"],
    ]) + "\n")  # fmt: skip

    L.append("## Intended use\n")
    L.append(
        "- A portfolio demonstration of an end-to-end risk-scoring pipeline: data quality, point-in-time features, honest evaluation, calibration, cost-based decisions and explanations."
    )
    L.append(
        "- Decision support in a simulation: it ranks transactions by estimated fraud probability and suggests ALLOW, REVIEW or BLOCK for a person or a downstream system to act on.\n"
    )
    L.append("## Out of scope\n")
    L.append(
        "- Any decision about real money, real customers or real accounts. The model has no validation on real data of any kind."
    )
    L.append(
        "- Automated blocking without human oversight, or use of reason codes as the sole explanation to a customer."
    )
    L.append("- Credit, identity, sanctions or other decisions that are not fraud triage.")
    L.append(
        "- Use on a different population, country, product or time period without new data, new validation and new costs.\n"
    )

    L.append("## Data\n")
    L.append(
        "Simulated by the repository's generator: customers, merchants, agents, devices and counties, with injected fraud episodes of eight patterns. Labels are *observed* labels: delayed (reports arrive up to 45 days later), noisy (some fraud is never reported and some reports are false) and separate from the hidden ground truth, which is used only in optional audits. See the [data dictionary](data-dictionary.md).\n"
    )
    rows = []
    for part in ("train", "validation", "test"):
        r = summ[part]
        rows.append(
            [
                part,
                r["first"][:10],
                r["last"][:10],
                f"{r['rows']:,}",
                f"{r['fraud']:,}",
                _pct(r["fraud_rate"], 2),
                f"{r['customers']:,}",
            ]
        )
    L.append(
        _table(
            [
                "Part",
                "First day",
                "Last day",
                "Transactions",
                "Fraud-labelled",
                "Fraud rate",
                "Customers",
            ],
            rows,
        )
        + "\n"
    )
    L.append(
        f"The model is imagined to be deployed on {bounds['val_start'][:10]}: training uses only transactions at least 45 days older, with the labels known on that day (the training part ends {bounds['train_end'][:10]}). The last 45 days of data are never evaluated because their labels are incomplete. Details: [ADR-012](adr/ADR-012-time-split-and-evaluation.md).\n"
    )

    L.append("## Inputs\n")
    L.append(
        "28 features computed from the transaction and strictly earlier history: velocity counts and sums, a 30-day personal baseline, novelty flags (new device, new recipient, location jump), inbound-transfer features, time of day, and a few customer attributes. Identifiers, merchant or agent fraud rates, labels and ground truth are not inputs. Missing history is passed as missing, which LightGBM handles natively.\n"
    )

    L.append("## Performance on the test window\n")
    L.append(
        f"PR-AUC (a random scorer scores the fraud rate, {_pct(summ['test']['fraud_rate'], 2)}); 95% intervals and paired differences are in [model-advanced.md](model-advanced.md) and are wide because the test window holds {summ['test']['fraud']} fraud-labelled transactions.\n"
    )
    L.append(_table(["Scorer", "Test PR-AUC", "Validation PR-AUC", "Calibration error (test)", "Brier score (test)", "Cost per 10,000 transactions, KES (ASSUMED costs)"], [
        [NAMES[k], f"{adv['test_pr_auc'][k]:.3f}", f"{adv['validation_pr_auc'][k]:.3f}",
         f"{ece[k]:.4f}" if k in ece else "n/a",
         f"{brier[k + ' calibrated']:.5f}" if k + " calibrated" in brier else "n/a",
         f"{cost[k]['point']:,.0f}" if k in cost else "n/a"]
        for k in NAMES
    ]) + "\n")  # fmt: skip
    best = min((k for k in NAMES if k in cost and k != "no_skill"), key=lambda k: cost[k]["point"])
    L.append(
        f"Allowing everything costs {base_cost:,.0f} KES per 10,000 transactions under the assumed costs, a fixed 0.5 cut-off on the raw score {cost['naive']['point']:,.0f}, and the shipped policy {cost['lightgbm']['point']:,.0f} ({_pct(1 - cost['lightgbm']['point'] / base_cost)} lower than allowing everything). The scorer with the lowest point estimate is {NAMES[best]}; the intervals overlap, so this is not a ranking. "
    )
    L.append(
        f"LightGBM's test PR-AUC ({adv['test_pr_auc']['lightgbm']:.3f}) is {'above' if adv['test_pr_auc']['lightgbm'] > adv['test_pr_auc']['random_forest'] else 'not above'} the random forest's ({adv['test_pr_auc']['random_forest']:.3f}); the paired difference with its interval is in the report. LightGBM was chosen in advance as the project's boosting model ([ADR-002](adr/ADR-002-lightgbm.md)) and kept because it gives exact explanations and handles missing history natively, not because it ranks better.\n"
    )

    L.append("## Decision policy and assumed costs\n")
    L.append(
        f"The action with the lowest expected cost is chosen from the calibrated probability and the amount. **All four numbers are assumptions**, not measurements: loss rate {cm['loss_rate']:g} of the amount, review cost {cm['review_cost']:g} KES, a review stops {_pct(cm['review_prevents'])} of fraud, a wrong block costs {cm['block_cost']:g} KES in friction. The report shows how the ranking of scorers changes with them ([cost-model.md](cost-model.md)).\n"
    )

    L.append("## Explanations\n")
    L.append(
        f"Exact TreeSHAP contributions (largest additivity error {exp['additivity_error_max']:.1e}). Largest average effect on all test transactions: {', '.join('`' + r['unit'] + '`' for r in imp_all[:3])}. On fraud-labelled rows: {', '.join('`' + r['unit'] + '`' for r in imp_fr[:3])}. Most ranking lost when shuffled: {', '.join('`' + r['unit'] + '`' for r in perm[:3])}. The ten largest effects on the validation and test windows share {ag['top10_overlap_val_test']} features over all rows and {ag.get('top10_overlap_fraud_rows_val_test', 'n/a')} over fraud-labelled rows. Reason codes list at most three risk-raising features per flagged transaction ({exp['n_flagged']:,} flagged on the test window). Details and cross-checks: [model-explanations.md](model-explanations.md).\n"
    )

    L.append("## Who gets flagged\n")
    if sl:
        hi = max(sl, key=lambda r: r["legit_flagged_per_10k"])
        lo = min(sl, key=lambda r: r["legit_flagged_per_10k"])
        L.append(
            f"Among customer groups with at least 500 test transactions, legitimate transactions are flagged most often for {hi['slice']} = {hi['value']} ({hi['legit_flagged_per_10k']:,.0f} per 10,000) and least often for {lo['slice']} = {lo['value']} ({lo['legit_flagged_per_10k']:,.0f} per 10,000). This is a descriptive check on synthetic segments, not a fairness assessment; the full table is in section 6 of the explanations report.\n"
        )
    L.append(
        "`segment` is a model input. A customer attribute can be a legitimate risk signal in a simulation and still be inappropriate to use or to cite to a person in practice; that would need a policy decision and a review before any real use.\n"
    )

    L.append("## Limitations\n")
    L.append(
        "- Synthetic data: relationships in it were written by the author, so good results show that the pipeline works, not that the model would work on real transactions."
    )
    L.append(
        f"- Few fraud cases: {summ['test']['fraud']} in the test window and {summ['validation']['fraud']} in validation, so differences between models are mostly not separable."
    )
    L.append(
        f"- Calibration was fitted on one window (fraud rate {_pct(summ['validation']['fraud_rate'], 2)}) and measured on another ({_pct(summ['test']['fraud_rate'], 2)}); it is expected to drift and has to be re-checked."
    )
    L.append(
        "- Costs are placeholders; reviews and blocks are modelled with fixed shares and ignore queues, delays, capacity and customers who leave after a wrong block."
    )
    L.append("- Labels are the observed ones: they miss some fraud and include some false reports.")
    L.append(
        "- Adversaries adapt; the model has not been tested against an attacker who knows the features."
    )
    L.append("- The explanations describe the fitted model, not causes.\n")

    L.append("## Monitoring and maintenance\n")
    L.append(
        "Not implemented yet. Planned: serving and logging (Phases 11 and 13), calibration and drift monitoring (Phases 14 and 15) and gated retraining (Phase 16). Until then this card describes a single trained model with no live checks.\n"
    )

    L.append("## Reproduce\n")
    L.append(
        "```powershell\n.\\scripts\\dev.ps1 generate\n.\\scripts\\dev.ps1 ingest\n.\\scripts\\dev.ps1 features\n.\\scripts\\dev.ps1 train\n.\\scripts\\dev.ps1 advanced\n.\\scripts\\dev.ps1 explain\n.\\scripts\\dev.ps1 card\n```\n"
    )
    return "\n".join(L) + "\n"


def write(models_dir: Path, out: Path) -> Path:
    text = build(models_dir)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return out
