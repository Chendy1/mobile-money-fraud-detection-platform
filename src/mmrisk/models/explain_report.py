"""Writes docs/model-explanations.md and its figures. Every number comes from the run."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import polars as pl

from mmrisk.models import explain as X
from mmrisk.models import figures_explain as F

FIG_DIR_NAME = "models"


@dataclass
class ExplainResult:
    text: str
    metrics: dict
    figures: list[Path]


def _pct(x: float, d: int = 0) -> str:
    return f"{100 * x:.{d}f}%"


def _signed(x: float, d: int = 2) -> str:
    return f"{x:+.{d}f}"


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _label(u: str) -> str:
    return X.LABELS.get(u, u)


def _case(
    test: pl.DataFrame, assess: pl.DataFrame, tb: dict, a: float, pos: int, title: str
) -> dict:
    row = test[pos]
    effects, texts = {}, {}
    for u, v in tb["units"].items():
        f = X.UNITS[u][0]
        effects[u] = float(v[pos] * a)
        texts[u] = f"{_label(u)}: {X._value_text(f, row[f][0])}"
    p = assess["risk_probability"][pos]
    return {
        "title": f"{title}\np = {p:.1%}, {assess['action'][pos]}, {row['amount_kes'][0]:,.0f} KES",
        "effects": effects,
        "texts": texts,
        "transaction_id": row["transaction_id"][0],
        "probability": float(p),
        "action": assess["action"][pos],
    }


def write(*, split, model, tb, glob_all, glob_fraud, perm, perm_groups, groups, dep, examples, test,
          assess, codes, metrics, report_path: Path, figures_dir: Path, focus) -> ExplainResult:  # fmt: skip
    figures_dir = Path(figures_dir)
    a = model.calibrator.a
    figs = [
        F.importance(glob_all, glob_fraud, perm, figures_dir / "08-importance.png"),
        F.dependence(dep, focus, figures_dir / "09-dependence.png"),
    ]
    labels = {
        "caught_fraud": "Caught fraud",
        "false_alarm": "False alarm",
        "missed_fraud": "Missed fraud",
    }
    cases = [
        _case(test, assess, tb, a, pos, labels[k]) for k, pos in examples.items() if pos is not None
    ]
    if cases:
        figs.append(F.examples(cases, figures_dir / "10-examples.png"))
    m = metrics
    ag = m["agreement"]
    perm_sorted = perm.sort("drop", descending=True)
    base_p = 1 / (1 + np.exp(-m["base_log_odds"]))
    imp_all = {r["unit"]: r for r in m["importance_all"]}
    imp_fr = {r["unit"]: r for r in m["importance_fraud_rows"]}
    pm = {r["unit"]: r for r in m["permutation"]}

    def top(df, k=3, col="unit"):
        return ", ".join(f"`{u}`" for u in df.head(k)[col].to_list())

    L: list[str] = []
    L.append("# Model explanations\n")
    L.append("> **All data is synthetic.** These are explanations of what the model does with its inputs, "
             "not of why a transaction is fraudulent: a feature with a large effect is not necessarily a "
             "cause, and correlated features share credit. Generated by `python -m mmrisk.models explain`; "
             "every number below is computed from the run.\n")  # fmt: skip

    # ---- key results ----------------------------------------------------------------------------
    L.append("## Key results\n")
    L.append(f"- **The explanations are exact for this model.** Each transaction's contributions plus the "
             f"base value reproduce the model's log-odds to within {m['additivity_error_max']:.1e} "
             f"(base value {m['base_log_odds']:.2f}, a probability of {_pct(base_p, 2)}). They come from "
             "LightGBM's own tree computation (TreeSHAP), not from an approximation.")  # fmt: skip
    L.append(f"- **Three measures of importance give different answers.** Averaged over all "
             f"{m['n_test']:,} test transactions the largest effects are {top(glob_all)}; averaged over the "
             f"{m['n_test_fraud_labelled']} fraud-labelled rows they are {top(glob_fraud)}; shuffling a "
             f"feature costs the most ranking quality for {top(perm_sorted)}. Rank correlation with the "
             f"shuffling measure: {_signed(ag['spearman_shap_all_vs_permutation'])} (all rows) and "
             f"{_signed(ag['spearman_shap_fraud_vs_permutation'])} (fraud rows).")  # fmt: skip
    if ag["spearman_shap_all_vs_permutation"] < ag["spearman_shap_fraud_vs_permutation"]:
        L.append("  The average over all rows is mostly the variation among ordinary transactions, which "
                 "the ranking of the few fraud cases hardly depends on; the fraud-row average is closer "
                 "to what the ranking uses.")  # fmt: skip
    L.append(f"- **Stable across time.** The ten largest average effects on the validation and test windows "
             f"share {ag['top10_overlap_val_test']} features over all rows (rank correlation "
             f"{_signed(ag['spearman_val_vs_test'])}) and {ag['top10_overlap_fraud_rows_val_test']} over "
             f"fraud-labelled rows (rank correlation {_signed(ag['spearman_fraud_rows_val_vs_test'])}, "
             f"{ag['n_validation_fraud_labelled']} validation and {m['n_test_fraud_labelled']} test fraud rows). "
             "The all-rows figure is high partly because the same ordinary-row features dominate in every window.")  # fmt: skip
    ab, base = m["ablation"], m["ablation_base"]
    seeds_txt = f"{base['seeds']} seed" + ("s" if base["seeds"] != 1 else "")
    if base["seeds"] > 1:
        worse = [r for r in ab if r["sd"] is not None and r["delta"] < -2 * r["sd"]]
        better = [r for r in ab if r["sd"] is not None and r["delta"] > 2 * r["sd"]]
        parts = []
        if worse:
            parts.append("removing " + ", ".join(f"`{r['unit']}` ({_signed(r['delta'], 3)})" for r in worse)
                         + " lowers it by more than twice the seed-to-seed spread")  # fmt: skip
        if better:
            parts.append("removing " + ", ".join(f"`{r['unit']}` ({_signed(r['delta'], 3)})" for r in better)
                         + " raises it by more than twice the spread, so the model is not helped by using "
                         "that feature on the validation window")  # fmt: skip
        tail = "; ".join(parts) if parts else "no removal changes it by more than twice the seed-to-seed spread, so no single feature is needed on its own"  # fmt: skip
        L.append(f"- **Refitting without a feature** (validation PR-AUC {base['val_pr_auc']:.3f} with all features, "
                 f"{seeds_txt}): {tail}.")  # fmt: skip
    neg = [r for r in m["permutation"] if r["drop"] < -max(2 * r["sd"], 0.005)]
    if neg:
        L.append("- **Shuffling made the ranking better** for " + ", ".join(f"`{r['unit']}` ({_signed(r['drop'], 3)})" for r in neg)
                 + " (by more than 0.005 PR-AUC): the model's use of that feature does not carry over to the test window.")  # fmt: skip
    L.append(f"- **Reason codes.** {m['n_flagged']:,} test transactions were flagged (review or block); "
             f"{_pct(m['reason_code_coverage'])} of them have at least one risk-raising feature to cite. "
             f"The most common leading reason is `{m['top_reason_among_flagged'][0]['feature']}` "
             f"({m['top_reason_among_flagged'][0]['len']:,} flagged transactions).")  # fmt: skip
    if m["patterns"]:
        pats = [p for p in m["patterns"] if p.get("expected_in_top3") is not None]
        if pats:
            worst = min(pats, key=lambda p: p["expected_in_top3"])
            best = max(pats, key=lambda p: p["expected_in_top3"])
            L.append(f"- **Does it use the signals each fraud pattern is built on?** (uses the hidden "
                     f"truth, see section 5.) For flagged transactions, one of the expected signals is among "
                     f"the top three reasons {_pct(best['expected_in_top3'])} of the time for {best['pattern']} "
                     f"({best['flagged']} flagged) and {_pct(worst['expected_in_top3'])} for {worst['pattern']} "
                     f"({worst['flagged']} flagged).")  # fmt: skip
    L.append("")

    # ---- 1 importance -----------------------------------------------------------------------------
    L.append("## 1. Which features does the model use?\n")
    L.append("![importance](figures/models/08-importance.png)\n")
    L.append("Three measures, because each answers a different question. *Effect on all rows* is the average "
             "size of a feature's push on the log-odds over every test transaction. *Effect on fraud-labelled "
             "rows* is the same average over the transactions labelled fraud. *Ranking lost when shuffled* "
             "is how much PR-AUC falls when that feature's values are shuffled among rows (spread: standard "
             f"deviation over {m['permutation_repeats']} shuffles; it shows shuffle noise, not the sampling "
             "uncertainty of the test window). Amount and its logarithm are judged as one feature.\n")  # fmt: skip
    rows = []
    for u in list(
        dict.fromkeys(
            glob_all.head(6)["unit"].to_list()
            + glob_fraud.head(6)["unit"].to_list()
            + perm_sorted.head(6)["unit"].to_list()
        )
    ):
        rows.append([f"`{u}`", f"{imp_all[u]['mean_abs']:.3f}", f"{imp_fr[u]['mean_abs']:.3f}",
                     f"{pm[u]['drop']:.3f}", _signed(imp_all[u]["mean_signed"], 3)])  # fmt: skip
    L.append(_table(["Feature", "Mean effect, all rows", "Mean effect, fraud rows",
                     "PR-AUC lost when shuffled", "Mean signed effect, all rows"], rows) + "\n")  # fmt: skip
    L.append("The effects are in log-odds before calibration; multiply by "
             f"{a:.2f} (the calibration slope) for the calibrated scale used in reason codes. A feature that "
             "matters for the typical row but not for the ranking (a large effect on all rows, a small loss "
             "when shuffled) mostly moves ordinary transactions up or down together and does little to "
             "separate fraud.\n")  # fmt: skip
    gr = {r["group"]: r for r in m["groups_all"]}
    gf = {r["group"]: r for r in m["groups_fraud_rows"]}
    gp = {r["unit"]: r for r in m["permutation_groups"]}
    L.append("By feature group (all features of a group together; the shuffling column moves the whole group at once, "
             "which is the fairer test when features are correlated, such as the velocity counts):\n")  # fmt: skip
    L.append(_table(["Group", "Share of effect, all rows", "Share of effect, fraud rows", "PR-AUC lost when the group is shuffled"],
                    [[g, _pct(gr[g]["share"]), _pct(gf[g]["share"]), f"{gp[g]['drop']:.3f}"]
                     for g in sorted(gr, key=lambda g: -gp[g]["drop"])]) + "\n")  # fmt: skip

    # ---- 2 how ---------------------------------------------------------------------------------------
    L.append("## 2. How does each feature change the score?\n")
    L.append("![dependence](figures/models/09-dependence.png)\n")
    L.append("Average calibrated effect at each value of the six features with the largest effect on fraud-labelled "
             "rows. Orange bars raise the estimated risk, blue bars lower it.\n")  # fmt: skip
    for u in focus:
        d = m["direction"].get(u)
        dd = dep[u]
        hi = dd.sort("mean_effect", descending=True).row(0, named=True)
        lo = dd.sort("mean_effect").row(0, named=True)
        part = f"- **{_label(u)}** (`{u}`): highest average effect at {hi['bin']} ({_signed(hi['mean_effect'])}, {hi['n']:,} rows), lowest at {lo['bin']} ({_signed(lo['mean_effect'])}, {lo['n']:,} rows)."  # fmt: skip
        if d is not None and abs(d) >= 0.3:
            part += f" Higher values {'raise' if d > 0 else 'lower'} the risk on the whole (rank correlation {_signed(d)})."
        elif d is not None:
            part += f" No steady direction over the whole range (rank correlation {_signed(d)})."
        L.append(part)
    L.append("")

    # ---- 3 reason codes -------------------------------------------------------------------------------
    L.append("## 3. Reason codes for single transactions\n")
    if cases:
        L.append("![examples](figures/models/10-examples.png)\n")
        L.append("The examples are chosen by fixed rules, not for being flattering: the blocked fraud with the "
                 "highest probability, the blocked legitimate transaction with the highest probability, and "
                 "the allowed fraud with the largest amount. Effects are on the calibrated log-odds and add "
                 "up (with the base value) to the transaction's calibrated log-odds.\n")  # fmt: skip
        ex_rows = []
        for c in cases:
            sub = codes.filter(pl.col("transaction_id") == c["transaction_id"]).sort("rank")
            reasons = (
                "; ".join(
                    f"{t} ({_signed(e)})" for t, e in zip(sub["text"], sub["effect"], strict=True)
                )
                or "none (not flagged)"
            )
            ex_rows.append([c["title"].split("\n")[0], c["transaction_id"], f"{c['probability']:.1%}", c["action"], reasons])  # fmt: skip
        L.append(
            _table(["Case", "Transaction", "Probability", "Action", "Top reasons"], ex_rows) + "\n"
        )
    L.append("How reason codes are produced: for a flagged transaction, the features with the largest "
             "positive effect, at most three, each shown as a label and the transaction's own value. "
             "They answer \"what pushed this score up\", not \"why is this fraud\". For a transaction the "
             "model allows, they are not meant to be shown. `RiskModel.explain(df)` returns the same table "
             "for any rows (Phase 11 serves it).\n")  # fmt: skip
    tr = pl.DataFrame(m["top_reason_among_flagged"]).head(6)
    L.append("Leading reason among flagged test transactions:\n")
    L.append(_table(["Feature", "Flagged transactions"], [[f"`{r['feature']}`", f"{r['len']:,}"] for r in tr.to_dicts()]) + "\n")  # fmt: skip

    # ---- 4 cross-checks -----------------------------------------------------------------------------
    L.append("## 4. Do the explanations hold up?\n")
    L.append("**Stability.** The same measure computed on the validation window and on the test window "
             "(different months, never used to fit the model). Over all rows the ten largest share "
             f"{ag['top10_overlap_val_test']} features (rank correlation {_signed(ag['spearman_val_vs_test'])}); over "
             f"fraud-labelled rows {ag['top10_overlap_fraud_rows_val_test']} (rank correlation "
             f"{_signed(ag['spearman_fraud_rows_val_vs_test'])}; {ag['n_validation_fraud_labelled']} validation and "
             f"{m['n_test_fraud_labelled']} test fraud rows, so the fraud-row figure is the noisier of the two).\n")  # fmt: skip
    L.append("**Refitting without a feature.** The same settings are refitted with the feature blanked out and "
             f"scored on the validation window only (the test window plays no part). Baseline: {base['val_pr_auc']:.3f} "
             f"PR-AUC (mean of {seeds_txt}). \"Seed spread\" is the standard deviation across seeds; "
             "a change smaller than about twice that is not distinguishable from refitting noise.\n")  # fmt: skip
    L.append(_table(["Feature removed", "Validation PR-AUC", "Change", "Seed spread"],
                    [[f"`{r['unit']}`", f"{r['val_pr_auc']:.3f}", _signed(r['delta'], 3), "n/a" if r['sd'] is None else f"{r['sd']:.3f}"]
                     for r in sorted(ab, key=lambda r: r["delta"])]) + "\n")  # fmt: skip
    both = [
        (r, pm[r["unit"]])
        for r in ab
        if r["unit"] in pm and pm[r["unit"]]["drop"] > 0.02 and r["delta"] >= 0
    ]
    if both:
        names = "; ".join(
            f"`{r['unit']}` loses {p['drop']:.3f} PR-AUC when shuffled on the test window, yet refitting without it changed validation PR-AUC by {_signed(r['delta'], 3)}"
            for r, p in both
        )
        L.append("**Shuffling and refitting can disagree.** " + names + ". The fitted model uses these features, but other features carry much of the same information, so it can do without them.\n")  # fmt: skip
    L.append("A feature can matter to the fitted model and still be replaceable: when its information is "
             "also carried by other features, removing it changes little. That is a reason to treat the "
             "importance tables as a description of this fitted model, not as a ranking of causes.\n")  # fmt: skip

    # ---- 5 patterns -----------------------------------------------------------------------------------
    if m["patterns"]:
        L.append("## 5. Audit against ground truth\n")
        L.append("> **This section uses the hidden ground truth, which a real team would not have.** Nothing here "
                 "influenced training, tuning, calibration or the decision rule.\n")  # fmt: skip
        L.append("For each true fraud pattern, among the test transactions the policy flagged: the features with "
                 "the largest average effect, and how often at least one of the signals the pattern's "
                 "description in the data dictionary implies (the author's reading of it, an assumption) is "
                 "among the three reasons.\n")  # fmt: skip
        rows = []
        for p in m["patterns"]:
            if p.get("leading_features"):
                rows.append([p["pattern"], f"{p['flagged']} of {p['rows']}", ", ".join(f"`{u}`" for u in p["leading_features"]), _pct(p["expected_in_top3"])])  # fmt: skip
            else:
                rows.append([p["pattern"], f"{p['flagged']} of {p['rows']}", "none flagged", "n/a"])
        L.append(
            _table(["Pattern", "Flagged", "Leading features", "Expected signal in top 3"], rows)
            + "\n"
        )
        L.append("Patterns with few rows give noisy percentages; read the counts first.\n")

    # ---- 6 slices --------------------------------------------------------------------------------------
    L.append("## 6. Who gets flagged?\n")
    L.append("The same policy, split by customer attributes available in the data. This is a descriptive check "
             "for uneven treatment, not a test of fairness: the segments are synthetic, the labels are the "
             "observed (noisy) ones, and the counts are small. \"Fraud flagged\" is the share of fraud-labelled "
             "transactions in the group that were reviewed or blocked (95% interval).\n")  # fmt: skip
    rows = []
    for r in m["slices"]:
        ff = "n/a" if r["fraud_flagged"] is None else f"{_pct(r['fraud_flagged'])} ({_pct(r['fraud_flagged_ci'][0])} to {_pct(r['fraud_flagged_ci'][1])})"  # fmt: skip
        rows.append([r["slice"], r["value"], f"{r['n']:,}", str(r["fraud_labelled"]), f"{r['flagged_per_10k']:,.0f}", f"{r['legit_flagged_per_10k']:,.0f}", ff])  # fmt: skip
    L.append(_table(["Attribute", "Value", "Transactions", "Fraud-labelled", "Flagged per 10,000", "Legitimate flagged per 10,000", "Fraud flagged"], rows) + "\n")  # fmt: skip
    leg = [r for r in m["slices"] if r["n"] >= 500]
    if leg:
        hi = max(leg, key=lambda r: r["legit_flagged_per_10k"])
        lo = min(leg, key=lambda r: r["legit_flagged_per_10k"])
        L.append(f"Among groups with at least 500 transactions, legitimate transactions are flagged most often in "
                 f"{hi['slice']} = {hi['value']} ({hi['legit_flagged_per_10k']:,.0f} per 10,000) and least often in "
                 f"{lo['slice']} = {lo['value']} ({lo['legit_flagged_per_10k']:,.0f} per 10,000). Some difference is "
                 "expected where the groups really behave differently and the model uses that behaviour "
                 "(`is_away_from_home` is a model input); whether a difference is acceptable is a business "
                 "decision this report cannot make.\n")  # fmt: skip

    L.append("## What this does not show\n")
    L.append("- The explanations describe this fitted model on synthetic data. They are not evidence about real fraud or real customers.")  # fmt: skip
    L.append("- Importance is not causation, and with correlated features the credit is shared in ways that depend on the fitted trees.")  # fmt: skip
    L.append("- The shuffling and refitting checks use one fitted model and a small number of fraud cases; differences that are small relative to the spread printed next to them should not be read.")  # fmt: skip
    L.append("- Reason codes are for flagged transactions and explain the score, not the customer's intent. A reason that cites a customer attribute (such as segment) would need review before being shown to a person.")  # fmt: skip
    L.append("- The slice table is descriptive and uses synthetic segments; it is not a fairness assessment.")  # fmt: skip
    text = "\n".join(L) + "\n"
    report_path = Path(report_path)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(text, encoding="utf-8")
    return ExplainResult(text, metrics, figs)
