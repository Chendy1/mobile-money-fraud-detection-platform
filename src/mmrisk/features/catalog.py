"""Renders docs/feature-catalog.md from the registry, so the documentation cannot drift."""

from __future__ import annotations

from mmrisk.features.registry import EXCLUDED, FEATURE_VERSION, FEATURES

HISTORY_TEXT = {
    "none": "the transaction itself",
    "customer": "the customer's earlier transactions",
    "network": "other customers' earlier transfers",
}


def render() -> str:
    lines = [
        "# Feature catalog",
        "",
        f"Feature set version **{FEATURE_VERSION}**. Generated by "
        "`python -m mmrisk.features catalog` from `mmrisk/features/registry.py`; do not edit by "
        "hand (a test fails if it is out of date).",
        "",
        "All features are computed from the transaction and strictly earlier history. "
        '"Earlier" means before the row in (timestamp, transaction_id) order; time windows '
        "exclude the row itself and any row with the same timestamp. No feature reads labels or "
        "ground truth. All data is synthetic.",
        "",
        "| Feature | Type | Group | Looks at | Description |",
        "|---|---|---|---|---|",
    ]
    for f in FEATURES:
        lines.append(
            f"| `{f.name}` | {f.dtype} | {f.group} | {HISTORY_TEXT[f.history]} | {f.description} |"
        )
    lines += ["", "## Deliberately not features", "", "| Input | Why |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in EXCLUDED.items()]
    lines += [
        "",
        "## Missing values",
        "",
        "Some features are null by design: no earlier transaction (`secs_since_prev_txn`), "
        "no earlier activity in 30 days (`avg_amount_30d`), fewer than 3 earlier transactions "
        "in 30 days (`amount_to_avg_30d`), or no inbound transfer yet "
        '(`secs_since_last_inbound`). A null means "not enough history", which is itself '
        "informative, so Phase 7 models must either handle nulls natively (LightGBM) or impute "
        "with an indicator (linear models); imputation values are learned from training data "
        "only.",
        "learned from training data only.",
        "",
    ]
    return "\n".join(lines)
