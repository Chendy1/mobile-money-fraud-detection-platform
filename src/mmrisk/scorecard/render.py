"""Turn the evaluations into docs/scorecard.md. Deterministic: same inputs, same bytes (ASCII only)."""

from __future__ import annotations

from collections import Counter

from mmrisk.scorecard.model import LEVELS, Evaluation, Evidence

_REAL = {"yes": "yes", "partly": "partly", "no": "no"}


def summary_counts(results: list[Evaluation]) -> Counter:
    return Counter(r.level for r in results)


def render(ev: Evidence, results: list[Evaluation]) -> str:
    counts = summary_counts(results)
    n = len(results)
    L: list[str] = []
    a = L.append
    a("# Evidence scorecard (Phase 27)")
    a("")
    a("<!-- generated by `python -m mmrisk.scorecard render`; do not edit by hand -->")
    a("")
    a(
        "Each area of the project is placed on an evidence ladder. The level is **computed** from files and "
        "from text found in the documents cited for it (`docs/scorecard.json`); it is not a grade and nothing "
        "is averaged. The ladder is this project's own design, not an industry standard, and a level says "
        "what has been *checked*, not how good the area is."
    )
    a("")
    a("## The ladder")
    a("")
    a("| Level | Meaning | How it is decided |")
    a("|---|---|---|")
    a("| E0 | not built | listed code is missing |")
    a("| E1 | built | every listed code path exists |")
    a("| E2 | built and tested in the sandbox | listed test files exist |")
    a(
        "| E3 | tests green in CI after the last change | the area's CI jobs exist in `ci.yml`, the area was last changed no later than the phase the latest green run covers, and that run is recorded in the verification page |"
    )
    a(
        "| E4 | run on the author's machine after the last change | the Windows full suite, or a specific run by the author, is recorded for a phase at or after the last change |"
    )
    a(
        "| E5 | checked against something the project did not write | real data, an outside review or real traffic. **No area has this**: the data is synthetic by design |"
    )
    a("")
    a("## Why it is built this way")
    a("")
    a(
        "- **No score out of ten.** An average would hide the one fact that matters, which rung is missing."
    )
    a(
        "- **Levels are computed.** A level is derived from files and from text found in the cited document, so it cannot be raised by editing a number. If cited evidence is not found, `check` fails."
    )
    a(
        "- **A rung is only earned if every rung below holds**, and only for changes up to the evidence: CI that ran before an area last changed does not count for it."
    )
    a(
        "- **The top rung stays empty on purpose.** Synthetic data cannot be validated against real fraud; saying so is the point."
    )
    a(
        "- **To raise a level**, add the evidence (a recorded CI run, a recorded run on your machine) to `docs/verification-status.md` and update `docs/scorecard.json`, then run `python -m mmrisk.scorecard render`."
    )
    a("")
    a("## Summary")
    a("")
    a(f"{n} areas. " + ", ".join(f"E{k}: {counts.get(k, 0)}" for k in range(6)) + ".")
    a("")
    a(
        f"Latest green CI run: {ev.ci_run_id}, covering work through Phase {ev.ci_covers_through_phase}. "
        f"Windows full suite on record: {ev.suite_what}."
    )
    a("")
    a("## Areas")
    a("")
    a("| Area | Phases | Level | Ran for real | Held back by |")
    a("|---|---|---|---|---|")
    for r in results:
        held = ""
        if r.level < 4 and r.notes:
            rung, _, why = r.notes[0].partition(" missing: ")
            held = f"{rung}: {why}"
        a(
            f"| {r.area.name} | {r.area.phases} | E{r.level} | {_REAL[r.area.ran_for_real]} | {held} |"
        )
    a("")
    a(
        '"Ran for real" means the thing ran outside a test: yes, it was run as a user would run it; partly, some of it; no, it has only been tested or validated statically.'
    )
    a("")
    a("## Detail")
    for r in results:
        x = r.area
        a("")
        a(f"### {x.name} (E{r.level}: {LEVELS[r.level]})")
        a("")
        a(x.summary)
        a("")
        a(f"- Last changed: Phase {x.last_phase} ({x.last_change}).")
        a(f"- Ran for real: {x.ran_for_real}. {x.real_note}")
        if x.resume:
            a("- Resume bullets that rest on it: " + ", ".join(x.resume) + ".")
        for note in r.notes:
            a(f"- Missing: {note}.")
        for lim in x.limits:
            a(f"- Limit: {lim}.")
        a(f"- To move it up: {x.next}")
    a("")
    return "\n".join(L) + "\n"
